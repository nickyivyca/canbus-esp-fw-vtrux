def holder_ok(txt=None):
    """The bench is ours when bench-holder.md's lock names us as the holder with
    no loan out, or names us in "Loaned to:" (the holder lent it). A holder of
    ours with the bench loaned to someone else is not ours. Returns (ok, who)."""
    if txt is None:
        try:
            txt = open(HOLDER, encoding="utf-8").read()
        except OSError:
            return False, "cannot read bench-holder.md"
    m = re.search(r"^\*\*Holder:\*\*\s*(.+)$", txt, re.M)
    who = m.group(1).strip() if m else None
    m = re.search(r"^\*\*Loaned to:\*\*\s*(.*)$", txt, re.M)
    loan = m.group(1).strip() if m else ""
    if loan.strip("- ") == "":
        return who == ME, who
    return loan.startswith(ME), "%s, loaned to %s" % (who, loan)


class Witness(threading.Thread):
    """Kvaser, normal mode: every frame and error frame, hardware and receipt time."""

    def __init__(self, can):
        super().__init__(daemon=True)
        self.bus = can.Bus(interface="kvaser", channel=0, bitrate=BITRATE)
        self.stop_flag = threading.Event()
        self.frames, self.errs = [], []
        self.lock = threading.Lock()

    def run(self):
        while not self.stop_flag.is_set():
            m = self.bus.recv(timeout=0.05)
            while m is not None:
                rx = time.time()
                with self.lock:
                    if m.is_error_frame:
                        self.errs.append((m.timestamp, rx))
                    else:
                        self.frames.append((m.timestamp, rx, m.arbitration_id, bytes(m.data).hex()))
                m = self.bus.recv(timeout=0.0)

    def close(self):
        self.stop_flag.set()
        self.join(timeout=2.0)
        self.bus.shutdown()

    def clocked(self):
        with self.lock:
            fr, er = list(self.frames), list(self.errs)
        lags = [rx - hw for hw, rx, _, _ in fr]
        if lags and abs(statistics.median(lags)) < 2.0:
            note = "kvaser_hw (median receipt lag %.4f s)" % statistics.median(lags)
            return [(hw, a, h) for hw, _, a, h in fr], [hw for hw, _ in er], note
        return [(rx, a, h) for _, rx, a, h in fr], [rx for _, rx in er], "receipt (hw not epoch)"


