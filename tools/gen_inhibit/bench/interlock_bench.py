def parse_scn(text):
    """{"frames": [(t_us, id, hex)], "modes": [(t_us, mode, offset)], "end": t_us,
    "refused": [lines]}. Comments and blank lines are skipped."""
    out = {"frames": [], "modes": [], "end": None, "refused": []}
    for ln in text.splitlines():
        s = ln.strip()
        if not s or s.startswith("#"):
            continue
        p = s.split()
        if p[0] == "f":
            dlc, hexs = int(p[3]), (p[4] if len(p) > 4 else "")
            if len(hexs) != 2 * dlc:
                out["refused"].append(s)
                continue
            out["frames"].append((int(p[1]), int(p[2], 16), hexs.lower()))
        elif p[0] == "mode":
            out["modes"].append((int(p[1]), int(p[2]), int(p[3])))
        elif p[0] == "end":
            out["end"] = int(p[1])
        else:
            out["refused"].append(s)
    if out["end"] is None and out["frames"]:
        out["end"] = out["frames"][-1][0] + 1000000
    return out


def stimulus_premise(parsed):
    """Adjacent identical 0x051 payloads in the stimulus. Must be 0: the judge
    attributes a 0x051 to the device when it repeats the next one."""
    c = [h for _, i, h in parsed["frames"] if i == 0x051]
    return sum(1 for a, b in zip(c, c[1:]) if a == b)


def write_scn(name, header, frames, modes, end):
    lines = ["# %s" % ln for ln in header] + ["#"]
    rows = [(t, 0, "mode %d %d %d" % (t, m, o)) for t, m, o in modes]
    rows += [(t, 1, "f %d %03X %d %s" % (t, i, len(h) // 2, h.upper())) for t, i, h in frames]
    rows.sort(key=lambda r: (r[0], r[1]))
    lines += [r[2] for r in rows] + ["end %d" % end]
    os.makedirs(STIM_DIR, exist_ok=True)
    path = os.path.join(STIM_DIR, name + ".scn")
    with open(path, "w", newline="\n", encoding="ascii") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


def stim_sha(path):
    """The host suite's stimulus hash: every non-comment line (run_tests.scn_hashes)."""
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for line in fh:
            if not line.lstrip().startswith(b"#"):
                h.update(line)
    return h.hexdigest()


def golden_pin(name):
    p = os.path.join(HOSTDIR, "golden", "stimulus.sha256")
    if not os.path.exists(p):
        return None
    for ln in open(p, encoding="utf-8"):
        f = ln.split()
        if len(f) >= 3 and not ln.startswith("#") and f[2] == name + ".scn":
            return f[0]
    return None


