def host_scn(name, gen_dir):
    """A host scenario, generated fresh into gen_dir."""
    if name.startswith("replay-"):
        sys.path.insert(0, HOSTDIR)
        import replay_stimulus_delta as RSD
        row = [r for r in RSD.REPLAYS if r[0] == name][0]
        _, log, chan, at, dur, note = row
        out = os.path.join(gen_dir, name + ".scn")
        cmd = [sys.executable, os.path.join(HOSTDIR, "from_capture.py"), os.path.join(LOGS, log),
               "--repo", ROOT, "--channel", str(chan), "--at", str(at), "--for", str(dur), "--out", out]
        if note:
            cmd += ["--note", note]
        r = subprocess.run(cmd, capture_output=True, text=True, cwd=HOSTDIR)
        if r.returncode != 0:
            raise RuntimeError("from_capture failed: %s" % (r.stdout + r.stderr)[-400:])
        return out
    p = os.path.join(gen_dir, name + ".scn")
    if not os.path.exists(p):
        r = subprocess.run([sys.executable, os.path.join(HOSTDIR, "make_scenarios.py"), "--out", gen_dir],
                           capture_output=True, text=True, cwd=HOSTDIR)
        if r.returncode != 0:
            raise RuntimeError("make_scenarios failed: %s" % (r.stdout + r.stderr)[-400:])
    return p


def slice_frames():
    import lowid_flood_skip_bench as LF
    lead = int(SLICE_LEAD_S * 1e6)
