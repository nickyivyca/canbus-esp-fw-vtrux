class Poller(threading.Thread):
    def __init__(self, LF, every=0.5):
        super().__init__(daemon=True)
        self.LF, self.every = LF, every
        self.samples = []
        self.stop_flag = threading.Event()

    def run(self):
        while not self.stop_flag.is_set():
            p = self.LF.page()
            self.samples.append((time.time(), None if p is None else {k: p.get(k) for k in PAGE_FIELDS}))
            self.stop_flag.wait(self.every)


def play(can, bus, parsed, t0p, sent):
    """Frames at their scenario times on the PCAN. t0p: perf_counter at t = 0."""
    for t_us, ident, hexs in parsed["frames"]:
        target = t0p + t_us / 1e6
        while True:
            left = target - time.perf_counter()
            if left <= 0:
                break
            if left > 0.002:
                time.sleep(left - 0.002)
        msg = can.Message(arbitration_id=ident, data=bytes.fromhex(hexs), is_extended_id=False)
        try:
            bus.send(msg, timeout=0.2)
            sent.append((time.time(), ident, hexs, 1))
        except Exception:
            sent.append((time.time(), ident, hexs, 0))


def poster(LF, modes, t0p, posts):
    for t_us, mode, off in modes:
        while time.perf_counter() < t0p + t_us / 1e6:
            time.sleep(0.001)
        rec = {"t_sched_s": t_us / 1e6, "mode": mode, "offset": off, "t_sent": time.time()}
        try:
            rec["ok"] = LF.dev_post("/gen_inhibit_set?mode=%d&offset=%d" % (mode, off))
        except Exception as e:
            rec["ok"] = False
            rec["error"] = "%s: %s" % (type(e).__name__, e)
        rec["t_ret"] = time.time()
        posts.append(rec)


def reboot(LF, timeout=60.0):
    before = LF.page() or {}
    t = time.time()
    try:
        LF.dev_post("/system_reboot", timeout=6)
    except Exception:
        pass
    time.sleep(3.0)
    while time.time() - t < timeout:
        p = LF.page()
        if p is not None and p.get("uptime_ms") is not None and \
                (before.get("uptime_ms") is None or p["uptime_ms"] < before["uptime_ms"]):
            return {"ok": p.get("mode") == 0, "s": round(time.time() - t, 1),
                    "uptime_ms": p.get("uptime_ms"), "reset_reason": p.get("reset_reason"),
                    "mode": p.get("mode")}
        time.sleep(1.0)
    return {"ok": False, "s": round(time.time() - t, 1)}


def x2_rule6(frames):
    counts, builds = {}, {}
    for _, i, h in frames:
        if i in X2_IDS:
            counts["0x%X" % i] = counts.get("0x%X" % i, 0) + 1
            if i == 0x7F7 and len(h) >= 8:
                b = "%08x" % int.from_bytes(bytes.fromhex(h[:8]), "little")
                builds[b] = builds.get(b, 0) + 1
    return {"frames": counts, "0x7F7_build_ids": builds}


SENDER_STALL_S = 0.1     # the interlock windows are 0.5 s (1.0 s for 0x617)


def sender_stalls(parsed, sent, limit=SENDER_STALL_S):
    """Per ID, the worst excess of a sent gap over the gap the stimulus planned.
    sent[j] is parsed["frames"][j] (play() appends one entry per frame, in order),
    so a CPU-starved sender shows here even when every frame reached the wire.
    A stall the stimulus did not plan can stale an interlock signal and make the
    device trip correctly on a case that expects nothing, so it voids the run.
    Returns ({"0x%03X": worst_s}, [ids over the limit])."""
    fr = parsed["frames"]
    if len(sent) != len(fr):
        return {}, ["sent %d of %d frames" % (len(sent), len(fr))]
    last, worst = {}, {}
    for (t_us, ident, _h), (ts, _i, _h2, _ok) in zip(fr, sent):
        if ident in last:
            p_us, p_ts = last[ident]
            x = (ts - p_ts) - (t_us - p_us) / 1e6
            k = "0x%03X" % ident
            worst[k] = max(worst.get(k, x), x)
        last[ident] = (t_us, ts)
    worst = {k: round(v, 4) for k, v in sorted(worst.items())}
    return worst, [k for k, v in worst.items() if v > limit]


def witness_stalls(parsed, frames, limit=SENDER_STALL_S):
    """The same excess as sender_stalls, read off the Kvaser (hardware time): per
    stimulus ID, the k-th frame witnessed is the k-th planned. 0x051 is left out
    (the device sends it too); every other stimulus ID has one sender, the PCAN.
    An ID seen a different number of times than planned cannot be paired and is
    listed as stalled with its counts. Returns ({"0x%03X": worst_s}, [stalled])."""
    plan, wit = {}, {}
    for t_us, ident, _h in parsed["frames"]:
        if ident != 0x051:
            plan.setdefault(ident, []).append(t_us / 1e6)
    for t, ident, _h in frames:
        if ident in plan:
            wit.setdefault(ident, []).append(t)
    worst, bad = {}, []
    for ident in sorted(plan):
        k = "0x%03X" % ident
        p, w = plan[ident], sorted(wit.get(ident, []))
        if len(p) != len(w):
            bad.append("%s planned %d seen %d" % (k, len(p), len(w)))
            continue
        if len(p) > 1:
            worst[k] = round(max((w[j] - w[j - 1]) - (p[j] - p[j - 1]) for j in range(1, len(p))), 4)
    return worst, bad + [k for k, v in worst.items() if v > limit]


ABOVE_NORMAL = 0x8000      # Windows ABOVE_NORMAL_PRIORITY_CLASS


def raise_priority():
    """esp-development.md "Builds during wall-clock tests" rule 4: the tester's
    stimulus sender runs above normal, never High or Realtime (they can starve the
    USB stack the CAN adapters need). Returns the class read back, as recorded."""
    if sys.platform != "win32":
        return "not windows: unchanged"
    import ctypes
    k = ctypes.windll.kernel32
    k.GetCurrentProcess.restype = ctypes.c_void_p
    h = k.GetCurrentProcess()
    k.SetPriorityClass(ctypes.c_void_p(h), ABOVE_NORMAL)
    got = k.GetPriorityClass(ctypes.c_void_p(h))
    return {0x20: "normal", 0x40: "idle", 0x80: "high", 0x100: "realtime", 0x4000: "below_normal",
            0x8000: "above_normal"}.get(got, "0x%X" % got)


def run_case(can, LF, info, parsed, power, stamp):
    name = info["case"]
    rec = {"when": stamp, "case": name, "stimulus": info, "power": power, "build": LF.build_id(),
           "witness": "Kvaser, normal mode", "sender": "PCAN, normal mode"}
    rec["reboot"] = reboot(LF)
    if not rec["reboot"].get("ok"):
        rec["verdict"] = "VOID: the WiCAN did not come back in mode 0 after the reboot"
        return rec
    rec["page_before"] = {k: (LF.page() or {}).get(k) for k in PAGE_FIELDS}
    pc = can.Bus(interface="pcan", channel="PCAN_USBBUS1", bitrate=BITRATE)
    wit = Witness(can)
    wit.start()
    time.sleep(1.0)
    pol = Poller(LF)
    pol.start()
    sent, posts = [], []
    try:
        t0p = time.perf_counter() + 0.5
        rec["t0_epoch"] = time.time() + 0.5
        th = threading.Thread(target=poster, args=(LF, parsed["modes"], t0p, posts), daemon=True)
        th.start()
        play(can, pc, parsed, t0p, sent)
        while time.perf_counter() < t0p + parsed["end"] / 1e6:
            time.sleep(0.01)
        th.join(timeout=10.0)
    finally:
        rec["page_end"] = {k: (LF.page() or {}).get(k) for k in PAGE_FIELDS}
        try:
            LF.dev_post("/gen_inhibit_set?mode=0")
        except Exception:
            pass
        time.sleep(0.5)
        pol.stop_flag.set()
        pol.join(timeout=3.0)
        frames, errs, clock = wit.clocked()
        wit.close()
        pc.shutdown()
    rec.update(posts=posts, samples=pol.samples, witness_clock=clock, witness_frames=len(frames),
               witness_error_frames=len(errs), sent_ok=sum(s[3] for s in sent),
               sent_failed=sum(1 for s in sent if not s[3]), x2_rule6=x2_rule6(frames))
    by = {}
    for _, i, _h, ok in sent:
        if ok:
            by[i] = by.get(i, 0) + 1
    seen = {}
    for _, i, _h in frames:
        seen[i] = seen.get(i, 0) + 1
    rec["sent_vs_seen"] = {"0x%03X" % i: [n, seen.get(i, 0)] for i, n in sorted(by.items())}
    rec["sender_worst_excess_s"], stalled = sender_stalls(parsed, sent)
    rec["witness_worst_excess_s"], wstalled = witness_stalls(parsed, frames)
    short = [k for k, (n, s) in rec["sent_vs_seen"].items() if k != "0x051" and s < n]
    os.makedirs(RUNS, exist_ok=True)
    wpath = os.path.join(RUNS, "interlock_%s_%s_witness.json.gz" % (name, stamp))
    with gzip.open(wpath, "wt", encoding="ascii") as fh:
        json.dump({"clock": clock, "frames": frames, "errs": errs, "sent": sent}, fh)
    rec["witness_file"] = os.path.basename(wpath)
    case = dict(BY_NAME[name][4])
    if "change_at_s" in info:
        case["cut_at_epoch"] = rec["t0_epoch"] + info["change_at_s"]
    if "resume_at_s" in info:
        case["resume_at_epoch"] = rec["t0_epoch"] + info["resume_at_s"]
    if "injected_hex" in info:
        case["alias"] = {info["injected_hex"]: info["original_hex"]}
    res = J.judge(info["judge"], frames, posts, pol.samples, case, sent=sent)
    if short:
        res["preconditions"].append({"name": "every sent frame on the wire", "ok": False,
                                     "detail": "fewer seen than sent: %s" % short})
        res["verdict"] = "INCONCLUSIVE"
    if stalled:
        res["preconditions"].append({"name": "no sender stall over %d ms" % (SENDER_STALL_S * 1000),
                                     "ok": False, "detail": "stalled: %s (worst excess %s)"
                                     % (stalled, rec["sender_worst_excess_s"])})
        res["verdict"] = "INCONCLUSIVE"
    if wstalled:
        res["preconditions"].append({"name": "no stimulus gap on the wire over %d ms beyond plan"
                                     % (SENDER_STALL_S * 1000), "ok": False,
                                     "detail": "%s (worst excess %s)" % (wstalled, rec["witness_worst_excess_s"])})
        res["verdict"] = "INCONCLUSIVE"
    # The orthogonal count: the content split's VCM frames must be exactly the
    # 0x051 the PCAN sent. Anything else means device frames were misattributed.
    if res["facts"].get("vcm_0x051") != by.get(0x051, 0):
        res["preconditions"].append({"name": "0x051 attribution matches the sender", "ok": False,
                                     "detail": "VCM by content %s, sent %s" % (res["facts"].get("vcm_0x051"),
                                                                               by.get(0x051, 0))})
        res["verdict"] = "INCONCLUSIVE"
    drop = [s for (t, s) in pol.samples if s and s.get("uptime_ms") is not None]
    ups = [s["uptime_ms"] for s in drop]
    if any(b < a for a, b in zip(ups, ups[1:])):
        res["preconditions"].append({"name": "no reset during the case", "ok": False,
                                     "detail": "uptime fell: a reset during the run (flag to the reviewer)"})
        res["verdict"] = "INCONCLUSIVE"
    rec["judged"] = res
    rec["verdict"] = res["verdict"]
    return rec


CARRIED = ("every sent frame on the wire", "no sender stall", "no stimulus gap", "no reset during the case")


def case_of(info):
    """The judge's case dict for a run, as run_case builds it."""
    name = info["case"]
    case = dict(BY_NAME[name][4])
    if "change_at_s" in info:
        case["cut_at_epoch"] = info["_t0_epoch"] + info["change_at_s"]
    if "resume_at_s" in info:
        case["resume_at_epoch"] = info["_t0_epoch"] + info["resume_at_s"]
    if "injected_hex" in info:
        case["alias"] = {info["injected_hex"]: info["original_hex"]}
    return case


def rejudge_file(path):
    """Judge a saved run again from its own files, with the sender-log attribution
    (2026-10-16). The run file is never changed: the result goes to
    <run>_rejudged_<stamp>.json. Preconditions that need the live stimulus (the
    sender and wire stall checks, the reset check, the sent-vs-seen count) are
    carried over from the original judgement by name; the 0x051 count is redone."""
    rec = json.load(open(path, encoding="ascii"))
    w = json.load(gzip.open(os.path.join(os.path.dirname(path), rec["witness_file"]), "rt"))
    frames = [tuple(x) for x in w["frames"]]
    sent = [tuple(x) for x in w["sent"]]
    info = dict(rec["stimulus"], _t0_epoch=rec["t0_epoch"])
    res = J.judge(info["judge"], frames, rec.get("posts") or [], rec.get("samples") or [],
                  case_of(info), sent=sent)
    old = (rec.get("judged") or {}).get("preconditions") or []
    for p_ in old:
        if not p_.get("ok") and p_["name"].startswith(CARRIED):
            res["preconditions"].append(dict(p_, carried=True))
            res["verdict"] = "INCONCLUSIVE"
    n_sent = sum(1 for _t, i, _h, ok in sent if ok and i == 0x051)
    if res["facts"].get("vcm_0x051") != n_sent:
        res["preconditions"].append({"name": "0x051 attribution matches the sender", "ok": False,
                                     "detail": "VCM by the sender log %s, sent %s"
                                     % (res["facts"].get("vcm_0x051"), n_sent)})
        res["verdict"] = "INCONCLUSIVE"
    stamp = time.strftime("%Y%m%dT%H%M%S")
    out = path[:-5] + "_rejudged_%s.json" % stamp
    rec2 = dict(rec, judged=res, verdict=res["verdict"], rejudged_from=os.path.basename(path),
                rejudged_at=stamp, previous_verdict=rec.get("verdict"))
    with open(out, "w", encoding="ascii") as fh:
        json.dump(rec2, fh, indent=1)
    return rec2, out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("action", choices=("list", "stimulus", "run", "rejudge"))
    ap.add_argument("cases", nargs="*")
    ap.add_argument("--power", help="how the WiCAN is powered, recorded as given (run)")
    ap.add_argument("--trial", metavar="LABEL",
                    help="run: NOT evidence (e.g. the build trial, esp-development.md \"Builds during "
                         "wall-clock tests\"); recorded with LABEL, written as interlock_trial_*.json")
    a = ap.parse_args(argv)
    if a.action == "rejudge":
        # cases are run FILES here: interlock_<case>_<stamp>.json
        for path in a.cases:
            rec2, out = rejudge_file(path)
            j = rec2["judged"]
            print("%-20s %-18s (was %s)  %s" % (rec2["case"], rec2["verdict"], rec2["previous_verdict"],
                                                os.path.basename(out)))
            for p_ in j["preconditions"] + j["checks"]:
                if not p_["ok"]:
                    print("    NOT MET: %s -- %s" % (p_["name"], str(p_.get("detail", ""))[:160]))
            at = j["facts"].get("attribution") or {}
            print("    attribution: %s offset %s s, residual max %s s, pairs by time %s, ambiguous %s"
                  % (at.get("method"), at.get("offset_s"), at.get("residual_max_s"),
                     at.get("pairs_by_time"), at.get("ambiguous_n")))
        return 0
    if a.action == "list":
        for n, row, kind, src, _ in CASES:
            print("%-20s %-14s %-12s %s" % (n, kind, src[0], row))
        return 0
    names = a.cases or [c[0] for c in CASES]
    bad = [n for n in names if n not in BY_NAME]
    if bad:
        print("unknown case(s): %s" % bad)
        return 2
    stamp = time.strftime("%Y%m%dT%H%M%S")
    gen = os.path.join(STIM_DIR, "host_%s" % stamp)
    os.makedirs(gen, exist_ok=True)
    built = []
    for n in names:
        info, parsed = build(n, gen)
        info["tester_repo_head"] = tester_head()
        why = stimulus_ok(info)
        print("%-20s %6d frames %7.1f s  sha %s  pin %s  %s" % (
            n, info["frames"], info["seconds"], info["sha256"][:12],
            {True: "match", False: "MISMATCH", None: "-"}[info.get("pin_match")],
            "OK" if not why else "REFUSED: " + "; ".join(why)))
        built.append((info, parsed, why))
    if a.action == "stimulus":
        path = os.path.join(STIM_DIR, "stimulus_check_%s.json" % stamp)
        with open(path, "w", encoding="ascii") as fh:
            json.dump([b[0] for b in built], fh, indent=1)
        print("wrote", path)
        return 1 if any(b[2] for b in built) else 0
    if not a.power:
        print("run needs --power")
        return 2
    ok, who = holder_ok()
    if not ok:
        print("REFUSED: bench-holder.md names %r as the holder" % (who,))
        return 2
    if any(b[2] for b in built):
        print("REFUSED: a stimulus failed its checks")
        return 2
    import can
    import lowid_flood_skip_bench as LF
    p = LF.page()
    if p is None or p.get("mode") != 0:
        print("REFUSED: the WiCAN must answer and be in mode 0")
        return 2
    prio = raise_priority()
    print("process priority:", prio)
    for info, parsed, _ in built:
        st = time.strftime("%Y%m%dT%H%M%S")
        rec = run_case(can, LF, info, parsed, a.power, st)
        rec["process_priority"] = prio
        kind = "interlock"
        if a.trial:
            rec["not_evidence"] = a.trial
            rec["verdict"] = "TRIAL, not evidence (judge said: %s)" % rec["verdict"]
            kind = "interlock_trial"
        print("    worst gap excess over plan, s: sender %s; Kvaser %s" % (
            rec.get("sender_worst_excess_s"), rec.get("witness_worst_excess_s")))
        path = os.path.join(RUNS, "%s_%s_%s.json" % (kind, info["case"], st))
        with open(path, "x", encoding="ascii", errors="replace") as fh:
            json.dump(rec, fh, indent=1)
        print("%-20s %s  (%s)" % (info["case"], rec["verdict"], os.path.basename(path)))
        for ch in (rec.get("judged") or {}).get("preconditions", []) + (rec.get("judged") or {}).get("checks", []):
            if not ch["ok"]:
                print("    NOT MET: %s -- %s" % (ch["name"], ch["detail"]))
    return 0


