def encode_sig(dbc, ident, hexs, sig, value):
    """The frame with one signal set to a physical value and EVERY OTHER BIT KEPT,
    at the frame's own length (cantools encodes the signal; its bits are spliced
    into the original). Encoding the whole decoded message instead zeroes every
    byte the DBC has no signal for -- 0x051's B0 and counter among them."""
    m = J.db(dbc).get_message_by_frame_id(ident)
    raw = bytes.fromhex(hexs)
    pad = raw + bytes(max(0, m.length - len(raw)))
    s = m.get_signal_by_name(sig)
    zero = {x.name: 0 for x in m.signals}
    mask = int.from_bytes(m.encode(dict(zero, **{sig: (1 << s.length) - 1}), scaling=False,
                                   strict=False), "big")
    zero_b = int.from_bytes(m.encode(zero, scaling=False, strict=False), "big")
    mask &= ~zero_b
    d = dict(zero)
    d[sig] = int(round((value - s.offset) / s.scale))
    val = int.from_bytes(m.encode(d, scaling=False, strict=False), "big") & mask
    out = (int.from_bytes(pad[:m.length], "big") & ~mask) | val
    return out.to_bytes(m.length, "big")[:len(raw)].hex()


def encode_mainc(hexs, stat):
    """0x440 with bcm_mainc_stat set to stat, every other bit kept."""
    return encode_sig(J.PT, 0x440, hexs, "bcm_mainc_stat", stat)


def build(case_name, gen_dir):
    """Write the case's stimulus; return its description."""
    name, row, kind, src, params = BY_NAME[case_name]
    info = {"case": name, "row": row, "judge": kind, "source": list(src)}
    if src[0] == "host":
        p = host_scn(src[1], gen_dir)
        text = open(p, encoding="utf-8").read()
        pin = golden_pin(src[1])
        sha = stim_sha(p)
        info.update(host_scenario=src[1], golden_pin=pin, pin_match=(pin == sha) if pin else None)
        parsed = parse_scn(text)
        path = write_scn(name, ["bench stimulus %s: host scenario %s, verbatim frames" % (name, src[1])],
                         parsed["frames"], parsed["modes"], parsed["end"])
        info["host_stimulus_sha256"] = sha
    elif src[0] == "derived":
        p = host_scn(src[1], gen_dir)
        parsed = parse_scn(open(p, encoding="utf-8").read())
        fr, modes = parsed["frames"], parsed["modes"]
        if src[2] == "close_all":
            fr = [(t, i, encode_mainc(h, 11) if i == 0x440 else h) for t, i, h in fr]
        elif src[2] == "modes_at":
            # Keep the first mode line (the arm); replace the rest. Every new one
            # must fall inside the frames, so the device is never left on a quiet bus.
            off = modes[0][2]
            modes = [modes[0]] + [(t, m, off) for t, m in src[3]]
            if max(t for t, _m in src[3]) >= fr[-1][0]:
                raise RuntimeError("modes_at: a mode line at or after the last frame")
        path = write_scn(name, ["bench stimulus %s: host scenario %s with %s %s"
                                % (name, src[1], src[2], src[3] if len(src) > 3 else "")],
                         fr, modes, parsed["end"])
        info["host_scenario"] = src[1]
    else:
        fr = slice_frames()
        t_change = int(SLICE_CHANGE_S * 1e6)
        if src[1] == "cut":
            fr = [(t, i, h) for t, i, h in fr if not (i in src[2] and t >= t_change)]
        elif src[1] == "fault":
            fr = [(t, i, (h[:14] + "ca") if (i == 0x617 and t >= t_change) else h) for t, i, h in fr]
        elif src[1] in ("rpm", "rpm_all"):
            t_from = t_change if src[1] == "rpm" else 0
            fr = [(t, i, encode_sig(J.PT, 0x054, h, "GENE_RotSpd", src[2]) if (i == 0x054 and t >= t_from) else h)
                  for t, i, h in fr]
        elif src[1] == "torque_all":
            fr = [(t, i, encode_sig(J.PTX, 0x051, h, "gen_torque_cmd", src[2]) if i == 0x051 else h)
                  for t, i, h in fr]
        elif src[1] == "drop051":
            fr = [(t, i, h) for t, i, h in fr if i != 0x051]
        elif src[1] == "stop":
            t_back = t_change + int(src[2] * 1e6)
            fr = [(t, i, h) for t, i, h in fr if not (t_change <= t < t_back)]
            info["resume_at_s"] = SLICE_CHANGE_S + src[2]
        else:
            k = next(n for n, (t, i, h) in enumerate(fr) if i == 0x051 and t >= t_change)
            t, i, h = fr[k]
            fr[k] = (t, i, h[:10] if src[2] < 6 else (h + "00" * (src[2] - len(h) // 2)))
            info.update(injected_hex=fr[k][2], original_hex=h)
        end = fr[-1][0] + 1000
        path = write_scn(name, ["bench stimulus %s: interlock slice, %s %s at %.1f s, armed at %.1f s"
                                % (name, src[1], src[2], SLICE_CHANGE_S, SLICE_ARM_S)],
                         fr, [(int(SLICE_ARM_S * 1e6), 3, 500)], end)
        info["change_at_s"] = SLICE_CHANGE_S
    parsed = parse_scn(open(path, encoding="ascii").read())
    info.update(file=os.path.relpath(path, HERE).replace("\\", "/"), sha256=stim_sha(path),
                frames=len(parsed["frames"]), modes=parsed["modes"],
                seconds=round(parsed["end"] / 1e6, 3), refused=parsed["refused"],
                adjacent_identical_0x051=stimulus_premise(parsed))
    return info, parsed


def stimulus_ok(info):
    why = []
    if info["refused"]:
        why.append("not playable on a bench: %s" % info["refused"][:3])
    if info["adjacent_identical_0x051"]:
        why.append("%d adjacent identical 0x051: device frames could not be told apart"
                   % info["adjacent_identical_0x051"])
    if info.get("pin_match") is False:
        why.append("stimulus differs from the host golden's pin")
    if not any(m == 3 for _, m, _ in info["modes"]):
        why.append("never armed")
    return why


