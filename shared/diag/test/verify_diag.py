#!/usr/bin/env python3
"""The tester's checks of shared/diag against SPEC.md D2-D4 (gen-inhibit tester, 2026-11-23,
stage (b) batch 2 of the shared-code port).

Each table is generated by the generator under test (tools/diag_table_gen.py) from a DBC,
and judged against that DBC as cantools reads it, never against the packers' own code:

  D3, the table is the DBC's   the C table (dumped by driver.c), the Python MESSAGES and the
                               header's <p>_<M>__<s>__BITS / __SIGNED / index and <p>_<M>__ID
                               constants each give every message's id, extended flag and
                               DLC, and every signal's start bit as written, length, byte
                               order, signedness and multiplexing, as cantools does.
  D3, misfits reported         for every message, value vectors with fitting, edge and
                               misfit values: the count and the mask are the signals packed
                               whose value is outside the signal's range, and the bytes are
                               cantools' encode of the same values with each misfit left 0,
                               so nothing is truncated into the frame. A selector that does
                               not fit gives -1 and a zeroed frame (diag_pack.h). The frame
                               the driver hands the C packer starts as A5 bytes, so a packer
                               that does not zero it shows.
  D4, C and Python agree       the same vectors through diag_pack_message() and
                               python/diag_pack.py's pack_message(): the same result and
                               bytes (and mask where the result is not -1); and the two
                               range functions give the same ranges as the DBC's widths.
  D2, the build id             for hashes made here (and all-0, all-FF, 80.., 01..):
                               diag_build_id_from() and diag_build_id() (over the driver's
                               descriptor) both give hash bytes 0-3, byte 0 most significant;
                               packed into the fixture's 32-bit unsigned Intel signal, the
                               wire bytes are hash[3], hash[2], hash[1], hash[0] and
                               cantools' unsigned value printed %08x reads as the hash's
                               first four bytes.

The DBCs: fixtures/verify.dbc (Intel and Motorola, signed and unsigned, 1 to 64 bits, a
3-byte frame, one multiplexer, an extended id, the build id's page), and each project's
published diag DBC as origin's main branch holds it (gen-inhibit's, the charge
interposer's), when this repo has them; a missing one is NOT RUN, never a pass.

The C side is built with ASan and UBSan. --diag DIR tests another shared/diag folder
(mutate.py's copies); the default is the one beside this folder. Work goes to the
worktree's scratch/diag-verify/<pid>/, removed afterwards. Exit 0 every check passed,
1 a check failed (the generator refusing a DBC and the C side crashing are failed checks),
2 refused (no cantools).

    python3.13 -B shared/diag/test/verify_diag.py [--diag DIR] [--n N] [--seed S] [--no-git]
"""

import argparse
import importlib.util
import os
import random
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DIAG = os.path.dirname(HERE)
WORKTREE = os.path.dirname(os.path.dirname(DIAG))
FIXTURE = os.path.join(HERE, "fixtures", "verify.dbc")
GIT_DBCS = [("gen-inhibit", "origin/gen-inhibit/main", "gen-inhibit/diag/vtrux-wican-diag.dbc"),
            ("charge-interposer", "origin/charge-interposer/main",
             "charge-interposer/diag/vtrux-interposer-diag.dbc")]
PREFIX = "vt"
INT64_MIN, INT64_MAX = -(1 << 63), (1 << 63) - 1
CC = os.environ.get("CC", "gcc")

FAILS = []
NOT_RUN = []


def check(label, ok, detail=""):
    print("  %-4s %s%s" % ("ok" if ok else "FAIL", label, "" if ok else "  -- " + str(detail)[:500]))
    if not ok:
        FAILS.append(label)


class Refused(Exception):
    pass


def load_py(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


# ---------------------------------------------------------------- the oracle: cantools

def oracle(db):
    """{message name: {"id", "extended", "dlc", "signals": {name: fields}}} from cantools."""
    out = {}
    for m in db.messages:
        sigs = {}
        for s in m.signals:
            if s.is_multiplexer:
                mux = -2
            elif s.multiplexer_ids:
                if len(s.multiplexer_ids) != 1:
                    raise Refused("%s.%s is under %d multiplexer values" % (m.name, s.name, len(s.multiplexer_ids)))
                mux = s.multiplexer_ids[0]
            else:
                mux = -1
            sigs[s.name] = {"start": s.start, "length": s.length, "big_endian": s.byte_order == "big_endian",
                            "is_signed": bool(s.is_signed), "mux": mux}
        out[m.name] = {"id": m.frame_id, "extended": bool(m.is_extended_frame), "dlc": m.length, "signals": sigs}
    return out


def sig_range(f):
    """The raw range a signal holds, by its width: diag_pack.h's, which takes int64_t, so an
    unsigned 64-bit signal tops out at INT64_MAX."""
    n = f["length"]
    if f["is_signed"]:
        return -(1 << (n - 1)), (1 << (n - 1)) - 1
    return 0, min((1 << n) - 1, INT64_MAX)


def expected(db, mname, osig, order, raw):
    """(result, mask or None, bytes) for raw (in the table's `order`), from the DBC alone."""
    m = db.get_message_by_name(mname)
    vals = dict(zip(order, raw))
    sel = next((n for n in order if osig[n]["mux"] == -2), None)
    dlc = m.length
    if sel is not None:
        lo, hi = sig_range(osig[sel])
        if not lo <= vals[sel] <= hi:
            return -1, None, bytes(dlc)
    packed = [n for n in order if osig[n]["mux"] < 0 or (sel is not None and osig[n]["mux"] == vals[sel])]
    data, mask, count = {}, 0, 0
    for n in packed:
        lo, hi = sig_range(osig[n])
        if lo <= vals[n] <= hi:
            data[n] = vals[n]
        else:
            data[n] = 0
            if osig[n]["mux"] != -2:
                count += 1
                mask |= 1 << order.index(n)
    return count, mask, flat_encode(m, packed, data)


def flat_encode(m, names, data):
    """cantools' encode of the signals `names` of message m, as one message without
    multiplexing (the selector a plain signal): a selector value the DBC has no signals
    for still encodes, and cantools places every bit."""
    import cantools
    sigs = []
    for n in names:
        s = m.get_signal_by_name(n)
        sigs.append(cantools.database.can.Signal(name=n, start=s.start, length=s.length,
                                                 byte_order=s.byte_order, is_signed=s.is_signed))
    flat = cantools.database.can.Message(frame_id=m.frame_id, name="flat", length=m.length, signals=sigs,
                                         is_extended_frame=m.is_extended_frame, strict=False)
    return bytes(flat.encode({n: data[n] for n in names}, scaling=False, padding=False, strict=False))


# ---------------------------------------------------------------- the C side

def write_consts(py, path):
    lines = []
    for m in py.MESSAGES:
        lines.append('printf("I %%s %%u %%d\\n", "%s", (unsigned)%s_%s__ID, (int)%s_%s);'
                     % (m["name"], PREFIX, m["name"], PREFIX, m["name"]))
        for s in m["signals"]:
            c = "%s_%s__%s" % (PREFIX, m["name"], s["name"])
            lines.append('printf("C %%s.%%s %%d %%d %%d\\n", "%s", "%s", (int)%s__BITS, (int)%s__SIGNED, (int)%s);'
                         % (m["name"], s["name"], c, c, c))
    open(path, "w").write("\n".join(lines) + "\n")


def build(work, diag):
    exe = os.path.join(work, "driver")
    cmd = [CC, "-std=c11", "-O1", "-g", "-Wall", "-Wextra", "-fsanitize=address,undefined",
           "-fno-sanitize-recover=undefined", "-I" + work, "-I" + os.path.join(diag, "include"),
           "-I" + os.path.join(HERE, "host"), '-DTBL_H="%s.h"' % PREFIX, "-DTBL=%s_messages" % PREFIX,
           "-DTBL_N=%s_MESSAGE_COUNT" % PREFIX, '-DCONSTS_INC="%s"' % os.path.join(work, "consts.inc"),
           "-o", exe, os.path.join(HERE, "driver.c"), os.path.join(work, PREFIX + ".c"),
           os.path.join(diag, "diag_pack.c"), os.path.join(diag, "diag_build_id.c")]
    r = subprocess.run(cmd, capture_output=True, text=True)
    return exe if r.returncode == 0 else None, r.stderr


def drive(exe, lines):
    r = subprocess.run([exe], input="\n".join(lines) + "\n", capture_output=True, text=True, timeout=600)
    if r.returncode != 0:
        raise RuntimeError("driver exit %d: %s" % (r.returncode, r.stderr[-1500:]))
    return r.stdout.splitlines()


def c_table(exe):
    out, cur = {}, None
    for ln in drive(exe, ["table"]):
        f = ln.split()
        if f[0] == "M":
            cur = out[f[1]] = {"id": int(f[2]), "extended": f[3] == "1", "dlc": int(f[4]), "n": int(f[5]),
                               "signals": {}, "order": []}
        elif f[0] == "S":
            cur["signals"][f[1]] = {"start": int(f[2]), "length": int(f[3]), "big_endian": f[4] == "1",
                                    "is_signed": f[5] == "1", "mux": int(f[6])}
            cur["order"].append(f[1])
    return out


def py_table(py):
    return {m["name"]: {"id": m["id"], "extended": bool(m["extended"]), "dlc": m["dlc"],
                        "signals": {s["name"]: {k: s[k] for k in ("start", "length", "big_endian", "is_signed", "mux")}
                                    for s in m["signals"]},
                        "order": [s["name"] for s in m["signals"]]}
            for m in py.MESSAGES}


def table_diffs(want, got):
    """Every difference between the oracle's table and a generated one, as text."""
    d = []
    for n in sorted(set(want) ^ set(got)):
        d.append("message %s only in the %s" % (n, "DBC" if n in want else "table"))
    for n in sorted(set(want) & set(got)):
        w, g = want[n], got[n]
        for k in ("id", "extended", "dlc"):
            if w[k] != g[k]:
                d.append("%s.%s: DBC %r, table %r" % (n, k, w[k], g[k]))
        for s in sorted(set(w["signals"]) ^ set(g["signals"])):
            d.append("%s.%s only in the %s" % (n, s, "DBC" if s in w["signals"] else "table"))
        for s in sorted(set(w["signals"]) & set(g["signals"])):
            for k, v in w["signals"][s].items():
                if g["signals"][s][k] != v:
                    d.append("%s.%s.%s: DBC %r, table %r" % (n, s, k, v, g["signals"][s][k]))
    return d


# ---------------------------------------------------------------- vectors

def value(rng, lo, hi, kind):
    if kind == "fit":
        return rng.randint(lo, hi)
    if kind == "edge":
        return rng.choice([lo, hi, 0 if lo <= 0 <= hi else lo, min(lo + 1, hi), max(hi - 1, lo)])
    if kind == "misfit":
        c = [x for x in (hi + 1, lo - 1, hi + rng.randint(2, 1000), lo - rng.randint(2, 1000))
             if INT64_MIN <= x <= INT64_MAX and not lo <= x <= hi]
        return rng.choice(c) if c else rng.randint(lo, hi)
    return rng.choice([INT64_MAX, INT64_MIN, -1])


def vectors(rng, osig, order, n):
    sel = next((s for s in order if osig[s]["mux"] == -2), None)
    pages = sorted({osig[s]["mux"] for s in order if osig[s]["mux"] >= 0})
    out = []
    for k in range(n):
        allfit = k % 3 == 0
        raw = []
        for s in order:
            lo, hi = sig_range(osig[s])
            if s == sel:
                r = rng.random()
                if r < 0.75 and pages:
                    v = rng.choice(pages)
                elif r < 0.85:
                    v = max(lo, min(hi, (max(pages) + 1) if pages else 0))     # a value with no signals
                elif allfit:
                    v = rng.randint(lo, hi)
                else:
                    v = value(rng, lo, hi, "misfit")
            else:
                kind = "fit" if allfit else rng.choices(["fit", "edge", "misfit", "far"], [45, 25, 20, 10])[0]
                v = value(rng, lo, hi, kind)
            raw.append(v)
        out.append(raw)
    return out


# ---------------------------------------------------------------- one DBC

def run_dbc(label, dbc_path, diag, work, rng, n, dp):
    import cantools
    print("\n%s (%s)" % (label, os.path.basename(dbc_path)))
    os.makedirs(work)
    r = subprocess.run([sys.executable, "-B", os.path.join(diag, "tools", "diag_table_gen.py"), dbc_path,
                        "--prefix", PREFIX, "--c-header", PREFIX + ".h", "--c-source", PREFIX + ".c",
                        "--python", PREFIX + ".py"], cwd=work, capture_output=True, text=True,
                       env=dict(os.environ, PYTHONDONTWRITEBYTECODE="1"))
    if r.returncode:
        raise Refused("the generator refused %s: %s" % (label, (r.stderr or r.stdout).strip()[-400:]))
    db = cantools.database.load_file(dbc_path, strict=False)
    want = oracle(db)
    py = load_py("vt_%s_%d" % (label.replace("-", "_"), os.getpid()), os.path.join(work, PREFIX + ".py"))
    write_consts(py, os.path.join(work, "consts.inc"))
    exe, err = build(work, diag)
    if not exe:
        check("%s: the driver builds on the generated C table" % label, False, err[-600:])
        return
    ct, pt = c_table(exe), py_table(py)
    d = table_diffs(want, ct)
    check("D3 %s: the C table is the DBC's (%d messages, %d signals)"
          % (label, len(want), sum(len(m["signals"]) for m in want.values())), not d, d[:4])
    d = table_diffs(want, pt)
    check("D3 %s: the Python table is the DBC's" % label, not d, d[:4])
    check("D4 %s: the C and Python tables list the signals in the same order" % label,
          {k: v["order"] for k, v in ct.items()} == {k: v["order"] for k, v in pt.items()})
    consts = drive(exe, ["consts"])
    bad = []
    for ln in consts:
        f = ln.split()
        if f[0] == "C":
            mname, sname = f[1].split(".", 1)
            o = want.get(mname, {}).get("signals", {}).get(sname)
            idx = pt[mname]["order"].index(sname) if mname in pt and sname in pt[mname]["order"] else None
            if not o or int(f[2]) != o["length"] or int(f[3]) != int(o["is_signed"]) or int(f[4]) != idx:
                bad.append(ln)
        elif f[0] == "I":
            if f[1] not in want or int(f[2]) != want[f[1]]["id"] or \
                    int(f[3]) != [m["name"] for m in py.MESSAGES].index(f[1]):
                bad.append(ln)
    check("D3 %s: the header's __BITS, __SIGNED, indexes and __ID are the DBC's" % label,
          not bad and len(consts) > 1, bad[:4])

    # ranges, then packing
    names = [m["name"] for m in py.MESSAGES]
    rq, rexp = [], []
    for mi, m in enumerate(py.MESSAGES):
        for si, s in enumerate(m["signals"]):
            rq.append("range %d %d" % (mi, si))
            rexp.append((m["name"], s["name"], sig_range(want[m["name"]]["signals"][s["name"]]),
                         (dp.signal_min(s), dp.signal_max(s))))
    got = drive(exe, rq)
    bad = [(m, s, e, g, p) for (m, s, e, p), g in zip(rexp, got) if (int(g.split()[1]), int(g.split()[2])) != e or p != e]
    check("D4 %s: diag_signal_min/max and signal_min/max give each signal's range by its width" % label,
          not bad, bad[:3])

    lines, cases = [], []
    for mi, m in enumerate(py.MESSAGES):
        order = pt[m["name"]]["order"]
        for raw in vectors(rng, want[m["name"]]["signals"], order, n):
            lines.append("pack %d %s" % (mi, " ".join(str(v) for v in raw)))
            cases.append((m, order, raw))
    got = drive(exe, lines)
    par, orc, misfits, fits, minus1 = [], [], 0, 0, 0
    for (m, order, raw), g in zip(cases, got):
        f = g.split()
        cr, cmask, cbytes = int(f[1]), int(f[2], 16), bytes.fromhex(f[3]) if len(f) > 3 else b""
        pr, pbytes, pmask = dp.pack_message(m, raw)
        if (cr, cbytes) != (pr, bytes(pbytes)) or (cr >= 0 and cmask != pmask):
            par.append((m["name"], raw, (cr, hex(cmask), cbytes.hex()), (pr, hex(pmask), bytes(pbytes).hex())))
        er, emask, ebytes = expected(db, m["name"], want[m["name"]]["signals"], order, raw)
        misfits += er > 0
        fits += er == 0
        minus1 += er == -1
        if (cr, cbytes) != (er, ebytes) or (er >= 0 and cmask != emask):
            orc.append((m["name"], dict(zip(order, raw)), "C", (cr, hex(cmask), cbytes.hex()),
                        "DBC", (er, hex(emask or 0), ebytes.hex())))
    check("D4 %s: C and Python give the same result, mask and bytes, %d vectors" % (label, len(cases)),
          not par, par[:2])
    check("D3 %s: the bytes are the DBC's encode, misfits counted, masked and left 0 "
          "(%d all fit, %d with misfits, %d refused selectors)" % (label, fits, misfits, minus1),
          not orc and fits and misfits, orc[:2])

    if "Verify_Build" in names:
        mi = names.index("Verify_Build")
        order = pt["Verify_Build"]["order"]
        hashes = ["00" * 32, "ff" * 32, "80" + "00" * 31, "01" + "00" * 31, "0123456789abcdef" * 4]
        hashes += ["%064x" % rng.getrandbits(256) for _ in range(60)]
        got = drive(exe, ["buildid %s" % h for h in hashes])
        bad = [(h, g) for h, g in zip(hashes, got) if g.split()[1:] != [h[:8], h[:8]]]
        check("D2: diag_build_id_from() and diag_build_id() give hash bytes 0-3, byte 0 most significant "
              "(%d hashes)" % len(hashes), not bad, bad[:2])
        lines = []
        for h in hashes:
            raw = [int(h[:8], 16) if s == "build_id" else 0 for s in order]
            lines.append("pack %d %s" % (mi, " ".join(map(str, raw))))
        got = drive(exe, lines)
        bad = []
        for h, g in zip(hashes, got):
            data = bytes.fromhex(g.split()[3])
            v = db.decode_message("Verify_Build", data, scaling=False)["build_id"]
            hb = bytes.fromhex(h)
            if data[:4] != bytes([hb[3], hb[2], hb[1], hb[0]]) or "%08x" % v != h[:8]:
                bad.append((h[:8], data.hex(), v))
        check("D2: packed, B0-B3 are hash[3..0] and the DBC's value printed %08x reads as the hash's first "
              "four bytes", not bad, bad[:2])


def git_dbc(rev, path, out):
    r = subprocess.run(["git", "-C", WORKTREE, "show", "%s:%s" % (rev, path)], capture_output=True)
    if r.returncode:
        return None
    open(out, "wb").write(r.stdout)
    return out


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--diag", default=DIAG, help="the shared/diag folder under test")
    ap.add_argument("--n", type=int, default=400, help="vectors per message")
    ap.add_argument("--seed", type=int, default=20261123)
    ap.add_argument("--no-git", action="store_true", help="the fixture only")
    a = ap.parse_args(argv)
    try:
        import cantools  # noqa: F401
    except ImportError as e:
        print("verify_diag: refused: %s" % e)
        return 2
    diag = os.path.abspath(a.diag)
    dp = load_py("diag_pack_under_test_%d" % os.getpid(), os.path.join(diag, "python", "diag_pack.py"))
    work = os.path.join(WORKTREE, "scratch", "diag-verify", str(os.getpid()))
    if os.path.exists(work):
        shutil.rmtree(work)
    os.makedirs(work)
    rng = random.Random(a.seed)
    print("shared/diag under test: %s; seed %d, %d vectors per message" % (diag, a.seed, a.n))
    try:
        todo = [("fixture", FIXTURE)]
        if not a.no_git:
            for label, rev, path in GIT_DBCS:
                p = git_dbc(rev, path, os.path.join(work, label + ".dbc"))
                if p:
                    todo.append((label, p))
                else:
                    print("\n%s: NOT RUN, no %s:%s in this repo" % (label, rev, path))
                    NOT_RUN.append(label)
        for label, p in todo:
            # A generator that refuses a DBC the spec allows, or a C side that crashes (ASan,
            # UBSan), is a failed check, never a refusal of the run.
            try:
                run_dbc(label, p, diag, os.path.join(work, label), rng, a.n, dp)
            except Refused as e:
                check("%s: the generator and cantools take the DBC" % label, False, e)
            except RuntimeError as e:
                check("%s: the C driver ran to the end" % label, False, e)
    finally:
        shutil.rmtree(work, ignore_errors=False)
        parent = os.path.dirname(work)
        if os.path.isdir(parent) and not os.listdir(parent):
            os.rmdir(parent)
    print("\n%s%s" % ("PASS" if not FAILS else "FAIL: %d check(s)" % len(FAILS),
                      "; NOT RUN: %s" % ", ".join(NOT_RUN) if NOT_RUN else ""))
    return 1 if FAILS else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
